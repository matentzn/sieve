"""Requirement traceability for the SIEVE profile.

Three inputs are joined here:

- ``requirements/mondo_requirements.tsv``: the requirement rows, extracted from the
  Mondo requirements workbook;
- ``requirements/traceability.yaml``: per requirement, the SEPIO design module, a
  disposition and the rationale;
- ``schema/sieve.yaml``: the schema elements, each carrying the requirement IDs it
  realises in ``annotations.requirements``.

:func:`collect_annotations` builds the reverse index (requirement -> elements);
:func:`render_markdown` produces the matrix published in
``docs/requirements-traceability.md``.
"""

import csv
from collections import defaultdict
from pathlib import Path
from typing import Any

import yaml
from linkml_runtime.utils.schemaview import SchemaView

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "schema" / "sieve.yaml"
CORE_SCHEMA = ROOT / "schema" / "sepio_core.yaml"
REQUIREMENTS_TSV = ROOT / "requirements" / "mondo_requirements.tsv"
TRACEABILITY_YAML = ROOT / "requirements" / "traceability.yaml"
DISPOSITIONS = ("modelled", "negative_constraint", "not_desired", "out_of_scope")
# Dispositions that must be realised by at least one annotated schema element.
ANNOTATED_DISPOSITIONS = ("modelled", "negative_constraint")


def split_ids(value: Any) -> list[str]:
    """Split a space-separated annotation value into IDs.

    >>> split_ids("C001  EINT.DIRECTION")
    ['C001', 'EINT.DIRECTION']
    >>> split_ids(None)
    []
    """
    return str(value).split() if value is not None else []


def load_requirements(path: Path = REQUIREMENTS_TSV) -> dict[str, dict[str, str]]:
    """Return the requirement rows keyed by requirement ID, in workbook order."""
    with path.open() as fh:
        return {row["id"]: row for row in csv.DictReader(fh, delimiter="\t")}


def load_traceability(path: Path = TRACEABILITY_YAML) -> dict[str, Any]:
    """Return the parsed traceability file (``modules`` and ``requirements``)."""
    with path.open() as fh:
        return yaml.safe_load(fh)


def _annotation(element: Any, key: str) -> Any:
    """Return the value of annotation ``key`` on a schema element, or None."""
    annotations = getattr(element, "annotations", None) or {}
    if key not in annotations:
        return None
    return annotations[key].value


def schema_elements(sv: SchemaView) -> list[tuple[str, Any]]:
    """Return (path, element) for every annotatable element defined in the profile.

    Paths are ``Class``, ``Class.slot`` (slot_usage or attribute), ``Enum`` and
    ``Enum.value``.
    """
    out: list[tuple[str, Any]] = []
    for name, cls in sv.all_classes(imports=False).items():
        out.append((name, cls))
        for slot_name, slot in {**(cls.slot_usage or {}), **(cls.attributes or {})}.items():
            out.append((f"{name}.{slot_name}", slot))
    for name, enum in sv.all_enums(imports=False).items():
        out.append((name, enum))
        for pv_name, pv in (enum.permissible_values or {}).items():
            out.append((f"{name}.{pv_name}", pv))
    return out


def collect_annotations(sv: SchemaView, key: str = "requirements") -> dict[str, list[str]]:
    """Map each ID found in annotation ``key`` to the element paths that carry it."""
    index: dict[str, list[str]] = defaultdict(list)
    for path, element in schema_elements(sv):
        for req_id in split_ids(_annotation(element, key)):
            index[req_id].append(path)
    return dict(index)


def render_markdown(sv: SchemaView | None = None) -> str:
    """Render the requirement -> module -> elements matrix as Markdown."""
    sv = sv or SchemaView(str(SCHEMA))
    requirements = load_requirements()
    trace = load_traceability()
    index = collect_annotations(sv)
    modules = trace["modules"]
    lines = [
        "# Requirements traceability: Mondo requirements to the SIEVE profile",
        "",
        "<!-- Generated by scripts/render_traceability.py; do not edit by hand. -->",
        "",
        "Each requirement from the Mondo requirements collection is assigned to a SEPIO design",
        "module and a disposition (`requirements/traceability.yaml`). The schema elements listed",
        "for a requirement are those annotated with its ID in `schema/sieve.yaml`.",
        "",
        "## SEPIO design modules",
        "",
        "| Module | SEPIO core classes | Description |",
        "|---|---|---|",
    ]
    for key, module in modules.items():
        core = ", ".join(f"`{c}`" for c in module["core_classes"])
        lines.append(f"| **{module['title']}** (`{key}`) | {core} | {' '.join(module['description'].split())} |")
    for key, module in modules.items():
        rows = [(rid, entry) for rid, entry in trace["requirements"].items() if entry["module"] == key]
        if not rows:
            continue
        lines += ["", f"## {module['title']}", "", "| Requirement | Title | Cur → Des | Disposition | Schema elements | Decisions | Rationale |", "|---|---|---|---|---|---|---|"]
        for rid, entry in rows:
            req = requirements[rid]
            elements = "<br>".join(f"`{p}`" for p in index.get(rid, [])) or "–"
            decisions = ", ".join(entry.get("decisions", [])) or "–"
            change = f"{req['current'] or '–'} → {req['desired']}"
            rationale = " ".join(str(entry["rationale"]).split())
            lines.append(f"| `{rid}` | {req['title']} | {change} | {entry['disposition']} | {elements} | {decisions} | {rationale} |")
    return "\n".join(lines) + "\n"
