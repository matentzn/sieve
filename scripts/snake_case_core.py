"""Derive schema/sepio_core.yaml (snake_case slots) from the canonical SEPIO core.

The canonical core (sepio-linkml ``src/sepio_linkml/schema/sepio_classes.yaml``) names
its slots in camelCase. SIEVE uses snake_case for every slot (class names unchanged),
agreed with the SEPIO maintainers. This script renames each attribute and pins its
original IRI with ``slot_uri``, so the RDF identity of every slot is unchanged: a
snake_case ``has_evidence_lines`` is still ``sepio-model:hasEvidenceLines``.

Usage::

    uv run python scripts/snake_case_core.py ../sepio-linkml/src/sepio_linkml/schema/sepio_classes.yaml
"""

import re
import sys
from pathlib import Path

import yaml

OUT = Path(__file__).resolve().parent.parent / "schema" / "sepio_core.yaml"
HEADER = """\
# GENERATED by scripts/snake_case_core.py from the canonical SEPIO core
# (sepio-linkml src/sepio_linkml/schema/sepio_classes.yaml). Do not edit by hand.
# Slots are snake_case; slot_uri keeps each slot's canonical camelCase IRI.
"""


def to_snake(name: str) -> str:
    """camelCase -> snake_case.

    >>> to_snake("hasEvidenceFromSources")
    'has_evidence_from_sources'
    >>> to_snake("id")
    'id'
    """
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def convert(core: dict) -> dict:
    """Rename every class attribute to snake_case, pinning the canonical IRI."""
    prefix = core["default_prefix"]
    for cls in (core.get("classes") or {}).values():
        attributes = cls.get("attributes") or {}
        renamed = {}
        for name, slot in attributes.items():
            slot = dict(slot or {})
            snake = to_snake(name)
            if snake != name:
                slot = {"slot_uri": f"{prefix}:{name}", **slot}
            renamed[snake] = slot
        if attributes:
            cls["attributes"] = renamed
    return core


def render(canonical: Path) -> str:
    """The derived core as YAML text."""
    core = yaml.safe_load(canonical.read_text(encoding="utf-8"))
    body = yaml.safe_dump(convert(core), sort_keys=False, allow_unicode=True, width=100)
    return HEADER + body


if __name__ == "__main__":
    OUT.write_text(render(Path(sys.argv[1])), encoding="utf-8")
    print(f"wrote {OUT}")
